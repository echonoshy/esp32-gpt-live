#!/usr/bin/env python3
"""Rebuild static UI fonts and the self-contained web wordmark (requires fonttools[woff])."""
import argparse
import base64
import re
import subprocess
import tempfile
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--body-font", type=Path, default=ROOT / ".tools/fonts/BarlowSemiCondensed-Medium.ttf")
parser.add_argument("--heading-font", type=Path, default=ROOT / ".tools/fonts/BarlowCondensed-BlackItalic.ttf")
parser.add_argument("--mono-font", type=Path, default=ROOT / ".tools/fonts/IBMPlexMono-Regular.ttf")
parser.add_argument("--brand-font", type=Path, default=ROOT / ".tools/fonts/Orbitron-Variable.ttf")
parser.add_argument("--converter", type=Path,
                    default=ROOT / ".tools/font-converter/node_modules/lv_font_conv/lv_font_conv.js")
args = parser.parse_args()


def instance(source, output, weight):
    font = TTFont(source, recalcTimestamp=False)
    if "fvar" in font:
        axes = {axis.axisTag: (weight if axis.axisTag == "wght" else
                              14 if axis.axisTag == "opsz" else axis.defaultValue)
                for axis in font["fvar"].axes}
        font = instantiateVariableFont(font, axes, inplace=True)
    font.save(output)


def convert(name, size, fonts, max_height):
    output = ROOT / f"firmware/main/fonts/{name}.c"
    subprocess.run(["node", str(args.converter), *fonts, "--size", str(size),
                    "--bpp", "4", "--format", "lvgl", "--lv-include", "lvgl.h",
                    "--no-compress", "--no-kerning", "-o", str(output)], check=True)
    source = output.read_text()
    source = re.sub(r"^ \* Opts:.*$", " * Generated by scripts/build_ui_fonts.py; see font licenses.",
                    source, flags=re.MULTILINE)
    output.write_text(source.rstrip() + "\n")
    height = int(re.search(r"\.line_height = (\d+)", source)[1])
    assert height <= max_height, (name, height)
    print(f"{name}: 4 bpp, line height {height} px")


with tempfile.TemporaryDirectory(prefix="mic-on-fonts-") as work:
    temp = Path(work)
    brand = temp / "brand.ttf"
    instance(args.brand_font, brand, 900)
    for size, font in ((14, args.body_font), (16, args.mono_font), (18, args.body_font), (22, args.heading_font)):
        convert(f"ui_font_{size}", size,
                ["--font", str(font), "--range", "0x20-0x7e"], {14: 18, 16: 20, 18: 23, 22: 26}[size])
    for size in (44, 52, 80):
        convert(f"ui_font_comic_{size}", size, ["--font", str(args.heading_font), "--symbols", ("SETTINGS" if size == 52 else "VOICE LIVE" if size == 80 else "VOICE LIVE SETTINGS")], size + 6)
    # Embed only the wordmark's six characters. No external font request on the device portal.
    font = TTFont(brand, recalcTimestamp=False)
    options = subset.Options()
    options.recalc_timestamp = False
    sub = subset.Subsetter(options=options)
    sub.populate(text="mic-on")
    sub.subset(font)
    font.flavor = "woff2"
    web = temp / "brand.woff2"
    font.save(web)
    rule = ('@font-face{font-family:MicOn;src:url(data:font/woff2;base64,' +
            base64.b64encode(web.read_bytes()).decode() +
            ') format("woff2");font-style:normal;font-weight:700;font-display:swap}')
    page = ROOT / "firmware/main/settings.html"
    html = page.read_text()
    marker = r'/\* mic-on-wordmark:start \*/.*?/\* mic-on-wordmark:end \*/'
    assert re.search(marker, html, re.S), "Missing wordmark CSS markers"
    html = re.sub(marker, '/* mic-on-wordmark:start */\n' + rule +
                  '\n/* mic-on-wordmark:end */', html, flags=re.S)
    # Share the comic heading with the offline phone portal.
    heading = TTFont(args.heading_font, recalcTimestamp=False)
    heading_sub = subset.Subsetter(options=options)
    heading_sub.populate(unicodes=range(32, 127))
    heading_sub.subset(heading)
    heading.flavor = "woff2"
    heading_web = temp / "comic.woff2"
    heading.save(heading_web)
    comic_rule = '@font-face{font-family:Comic;src:url(data:font/woff2;base64,' + base64.b64encode(heading_web.read_bytes()).decode() + ') format("woff2");font-style:italic;font-weight:900;font-display:swap}'
    html = re.sub(r'/\* mic-on-comic:start \*/.*?/\* mic-on-comic:end \*/\n?', '', html, flags=re.S)
    html = html.replace(':root{', '/* mic-on-comic:start */\n' + comic_rule + '\n/* mic-on-comic:end */\n:root{', 1)
    page.write_text(html)
    print(f"Web wordmark: {web.stat().st_size} bytes, embedded WOFF2")
