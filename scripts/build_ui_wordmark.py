#!/usr/bin/env python3
"""Encode the approved wordmark specimen as a small flash-resident LVGL image.

Pillow is only needed when regenerating; firmware builds use the checked-in C.
The crop selects the approved large logo, preserving its solid n geometry.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/brand/mic-on-wordmark-italic-solid-n.png"
TARGET = ROOT / "firmware/main/assets/ui_wordmark.c"


def main():
    source = Image.open(SOURCE).convert("RGB")
    assert source.size == (1536, 1024), "Recheck the crop for a different specimen"
    crop = source.crop((52, 185, 1484, 538))
    # Separate the paper and magenta ink from the dark specimen background.
    # Encode coverage first so downsampling preserves thin counters and edges.
    paper = Image.new("L", crop.size)
    accent = Image.new("L", crop.size)
    paper.putdata([255 if min(r, g, b) > 120 else 0 for r, g, b in crop.getdata()])
    accent.putdata([255 if r > 120 and g < 100 and b > 35 else 0
                    for r, g, b in crop.getdata()])
    size = (124, 31)
    paper = paper.resize(size, Image.Resampling.LANCZOS)
    accent = accent.resize(size, Image.Resampling.LANCZOS)
    background, cream, pink = (20, 20, 20), (243, 238, 219), (245, 0, 101)
    data = bytearray()
    for a, b in zip(paper.getdata(), accent.getdata()):
        color = tuple(round((base * (255 - min(255, a + b)) + c * a + p * b) / 255)
                      for base, c, p in zip(background, cream, pink))
        r, g, blue = color
        rgb565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (blue >> 3)
        data.extend(rgb565.to_bytes(2, "little"))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in data[i:i+16]) + ","
            for i in range(0, len(data), 16)]
    TARGET.write_text('/* Generated by scripts/build_ui_wordmark.py. */\n#include "lvgl.h"\n\n'
        'static const uint8_t wordmark_pixels[] = {\n' + "\n".join(rows) + '\n};\n\n'
        'const lv_image_dsc_t ui_wordmark = {\n'
        '    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,\n'
        '               .w = 124, .h = 31, .stride = 248},\n'
        '    .data_size = sizeof(wordmark_pixels),\n'
        '    .data = wordmark_pixels,\n};\n')
    print(f"Encoded {size[0]}x{size[1]} wordmark: {len(data)} bytes")


if __name__ == "__main__":
    main()
